#!/usr/bin/env python3
"""Deletes every compiled artifact the last cargo build did not use.

Cargo never removes an artifact it no longer needs. Each dependency bump,
feature change or toolchain update leaves the previous compiled crates behind
in target/<profile>/{deps,build,.fingerprint}, so target/ only ever grows.

Every unit cargo builds is stored under a name ending in a 16-hex-digit hash
(deps/libserde-0123456789abcdef.rlib, build/ring-<hash>/out,
.fingerprint/serde-<hash>). Given the JSON messages of a build, which list the
files of every unit -- including the ones that were already fresh -- anything
in those directories whose hash is not in the list belongs to an older build.
The workspace's own crates are always kept: their final binaries and libraries
are copied out without a hash, so the list cannot vouch for them, and they are
small next to the dependencies.

Usage: prune-target.py <cargo-messages.json> [--dry-run]
"""

import json
import os
import re
import shutil
import sys

HASH = re.compile(r"-([0-9a-f]{16})(?=[./]|$)")
UNIT_DIRS = ("deps", "build", ".fingerprint")
# Output of `pnpm dmg` / tauri build; regenerated by every bundling run.
OLD_OUTPUTS = ("bundle",)


def used_units(messages_path):
    """Returns ({hash}, {profile dir}, {local crate name}) from cargo's JSON."""
    hashes, profiles, local = set(), set(), set()
    with open(messages_path) as f:
        for line in f:
            try:
                msg = json.loads(line)
            except ValueError:
                continue
            if (msg.get("package_id") or "").startswith("path+"):
                target = msg.get("target") or {}
                local.add(norm(target.get("name") or ""))
                # build/<package>-<hash> is named after the package.
                local.add(norm(msg["package_id"].split("#")[-1].split("@")[0]))
            paths = list(msg.get("filenames") or [])
            paths += [msg.get("executable") or "", msg.get("out_dir") or ""]
            for path in paths:
                hashes.update(HASH.findall(path))
                for unit_dir in UNIT_DIRS:
                    marker = os.sep + unit_dir + os.sep
                    if marker in path:
                        profiles.add(path.split(marker)[0])
    return hashes, profiles, local


def norm(name):
    return name.replace("-", "_")


def crate_of(entry):
    """libserde_json-<hash>.rlib -> serde_json"""
    stem = HASH.split(entry, maxsplit=1)[0]
    if stem.startswith("lib"):
        stem = stem[3:]
    return norm(stem)


def size(path):
    if os.path.islink(path) or not os.path.isdir(path):
        return os.lstat(path).st_size
    total = 0
    for root, _, files in os.walk(path):
        for name in files:
            try:
                total += os.lstat(os.path.join(root, name)).st_size
            except OSError:
                pass
    return total


def remove(path):
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path, ignore_errors=True)
    else:
        os.remove(path)


def main(argv):
    if len(argv) < 2 or argv[1].startswith("-"):
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    dry_run = "--dry-run" in argv[2:]
    hashes, profiles, local = used_units(argv[1])
    if not hashes:
        # A failed or empty build lists nothing; pruning would wipe it all.
        print("prune-target: no artifacts in build output, skipping", file=sys.stderr)
        return 0

    freed = count = 0
    for profile in sorted(profiles):
        stale = []
        for unit_dir in UNIT_DIRS:
            directory = os.path.join(profile, unit_dir)
            if not os.path.isdir(directory):
                continue
            for name in os.listdir(directory):
                match = HASH.search(name)
                if (
                    match
                    and match.group(1) not in hashes
                    and crate_of(name) not in local
                    and norm(HASH.split(name, maxsplit=1)[0]) not in local
                ):
                    stale.append(os.path.join(directory, name))
        stale += [
            os.path.join(profile, name)
            for name in OLD_OUTPUTS
            if os.path.exists(os.path.join(profile, name))
        ]
        for path in stale:
            freed += size(path)
            count += 1
            if not dry_run:
                remove(path)

    verb = "would free" if dry_run else "freed"
    print(f"prune-target: {verb} {freed / 2**30:.1f} GB ({count} stale entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
